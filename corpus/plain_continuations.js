function detectPoliteStyle(editorText = '') {
  const clean = String(editorText || '').trim();
  if (!clean) return false;
  const nonQuoteLines = clean
    .split(/\n+/)
    .map(l => l.trim())
    .filter(l => l && !QUOTE_BLOCK_RE.test(l));
  const sample = nonQuoteLines.length > 0 ? nonQuoteLines.join(' ') : clean;
  const polite = (sample.match(/(습니다|ㅂ니다|해요|예요|네요|군요|까요|죠|어요|아요)[.?!]?(?=\s|$)/g) || []).length;
  const plain = (sample.match(/(다|는다|았다|었다|였다|리라|구나|던가)[.?!]?(?=\s|$)/g) || []).length;
  return polite > plain;
}

