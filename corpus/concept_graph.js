function inferConcepts(text = '', extraTags = '') {
  const primary = [];
  const secondary = [];
  for (const [name, def] of Object.entries(CONCEPTS)) {
    if (def.keywords.test(text)) {
      primary.push(name);
    } else if (extraTags && def.keywords.test(extraTags)) {
      secondary.push(name);
    }
  }
  const merged = [...primary, ...secondary];
  if (merged.length === 0) {
    merged.push('숙고·기다림');
  }
  return merged.slice(0, 2);
}

function getAntithesisConcepts(concepts = []) {
  const out = [];
  for (const c of concepts) {
    const anti = CONCEPTS[c] && CONCEPTS[c].antithesis;
    if (anti && !out.includes(anti)) out.push(anti);
  }
  return out;
}

function extractAuthorFromSource(source = '') {
  const clean = String(source).trim();
  if (!clean) return '작자 미상';
  if (/구약성경/.test(clean)) return '구약성경';
  if (/신약성경/.test(clean)) return '신약성경';
  if (/숫타니파타|법구경/.test(clean)) return '초기 불교 경전';
  if (/금강경|반야심경|화엄경/.test(clean)) return '대승 불교 경전';
  if (/바가바드 기타/.test(clean)) return '바가바드 기타';
  return clean.split(',')[0].replace(/[《》〈〉]/g, '').trim() || '작자 미상';
}

function inferLineage(author = '', cat = '철학') {
  if (AUTHOR_LINEAGE[author]) return AUTHOR_LINEAGE[author];
  if (cat === '경전') return '종교·영성 경전';
  if (cat === '문학') return '세계·한국 문학';
  return '동서양 철학';
}

