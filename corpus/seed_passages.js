function buildSeedPassages() {
  const {
    inferConcepts,
    extractAuthorFromSource,
    inferLineage
  } = require('./concept_graph');

  const combined = [];
  const seenTexts = new Set();

  for (const item of [...PASSAGES_LEGACY, ...EXTRA_PASSAGES]) {
    const text = (item.text || '').trim();
    if (!text || seenTexts.has(text)) continue;
    seenTexts.add(text);

    const source = (item.source || '').trim();
    const cat = item.cat || '철학';
    const author = item.author || extractAuthorFromSource(source);
    const lineage = item.lineage || inferLineage(author, cat);
    const tagsPattern = item.tags instanceof RegExp
      ? item.tags.source
      : String(item.tags || '');
    const concepts = Array.isArray(item.concepts) && item.concepts.length > 0
      ? item.concepts
      : inferConcepts(text, tagsPattern);

    combined.push({
      text,
      author,
      source,
      cat,
      lineage,
      concepts,
      tagsPattern
    });
  }

  return combined;
}

module.exports = { buildSeedPassages };
